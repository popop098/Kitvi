const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const { join } = require('node:path');
const { writeFileSync } = require('node:fs');
let win;
const js = code => win.webContents.executeJavaScript(code).catch(error => { throw Error(code + '\n' + error.message); });
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(code, label) { const start = Date.now(); while (Date.now() - start < 8000) { if (await js(code)) return; await wait(30); } throw Error('Timed out: ' + label); }
const button = label => `[...document.querySelectorAll('button')].find(button => button.textContent.trim() === ${JSON.stringify(label)})`;
const click = expression => js(`(()=>{const target=${expression};if(!target || target.disabled || target.getAttribute('aria-disabled')==='true')throw Error('Unavailable target: '+${JSON.stringify(expression)});target.focus();target.click()})()`);
const modalButton = label => `[...document.querySelector('dialog').querySelectorAll('button')].find(button => button.textContent.trim() === ${JSON.stringify(label)})`;
const report = { result: 'FAIL', checks: [] };
const check = name => report.checks.push(name);
const watchdog = setTimeout(() => { console.error('UI verification timeout'); app.exit(1); }, 45000);
app.whenReady().then(async () => {
  try {
    win = new BrowserWindow({ width: 1200, height: 900, show: false, webPreferences: { contextIsolation: true, nodeIntegration: false, sandbox: true, backgroundThrottling: false, offscreen: true } });
    win.webContents.on('console-message', (event, _level, message) => console.log('renderer:', event.message || message));
    await win.loadFile(join(__dirname, '../.cache/plugin-consent-ui/index.html'));
    await until(`!!document.querySelector('input[aria-label="플러그인 사용"]')`, 'global plugin usage switch');
    assert.equal(await js(`document.querySelector('input[aria-label="플러그인 사용"]').checked`), false);
    assert.equal(await js(`document.querySelectorAll('iframe').length`), 0);
    assert.equal(await js(`(${button('업데이트 확인')}).getAttribute('aria-disabled')`), 'true');
    await js(`(${button('업데이트 확인')}).click()`);
    assert.equal(await js('window.fixture.calls.filter(call=>call[0]==="updates").length'), 0);
    await click(button('가져오기')); await until('!!document.querySelector(".plugin-preview")', 'install metadata');
    await click(button('확인하고 설치')); await until('!document.querySelector(".plugin-preview")', 'install reviewed');
    assert.equal(await js('window.fixture.state().plugins[0].enabled'), false);
    assert.equal(await js('window.fixture.state().plugins[0].needsConsent'), true);
    check('metadata install while globally off remains pending activation');
    await click(`document.querySelector('input[aria-label="플러그인 사용"]')`);
    await until('!!document.querySelector("dialog[open]")', 'first-use notice');
    assert.match(await js('document.querySelector("dialog").textContent'), /외부 개발자/);
    assert.equal(await js('document.querySelector("dialog").contains(document.activeElement)'), true);
    win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' });
    win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Escape' });
    await until('!document.querySelector("dialog")', 'Escape closes notice');
    assert.equal(await js('document.activeElement.getAttribute("aria-label")'), '플러그인 사용');
    await click(`document.querySelector('input[aria-label="플러그인 사용"]')`); await until('!!document.querySelector("dialog[open]")', 'first-use after Escape');
    await click(modalButton('취소')); await until('!document.querySelector("dialog")', 'first-use cancellation');
    assert.equal(await js('window.fixture.calls.filter(call=>call[0]==="system").length'), 0);
    await click(`document.querySelector('input[aria-label="플러그인 사용"]')`); await until('!!document.querySelector("dialog[open]")', 'first-use repeat');
    await click(modalButton('확인하고 플러그인 사용')); await until('window.fixture.state().system.enabled', 'global gate accepted');
    assert.deepEqual(await js('window.fixture.calls.find(call=>call[0]==="system")'), ['system', true, true]);
    check('first global notice can be cancelled and explicitly accepted');
    await click(`document.querySelector('input[aria-label="Consent fixture 사용"]')`); await until('!!document.querySelector("dialog[open]")', 'per-plugin activation notice');
    const copy = await js('document.querySelector("dialog").textContent');
    for (const text of ['Example publisher', 'publisher@example.com', 'example/consent-fixture', '설정 저장', '다운로드 폴더', '직접 입력', '검증']) assert(copy.includes(text), text);
    await click(modalButton('취소')); await until('!document.querySelector("dialog")', 'activation cancellation');
    assert.equal(await js('window.fixture.calls.filter(call=>call[0]==="accept").length'), 0);
    await click(`document.querySelector('input[aria-label="Consent fixture 사용"]')`); await until('!!document.querySelector("dialog[open]")', 'activation repeat');
    await click(modalButton('동의하고 활성화')); await until('window.fixture.state().plugins[0].enabled', 'activation accepted');
    await click(button('열기')); await until('!!document.querySelector("iframe")', 'consented plugin frame');
    await js(`(()=>{const source=document.querySelector('iframe').contentWindow;window.fixture.emit({system:{enabled:false,acceptedAt:new Date().toISOString()}});window.dispatchEvent(new MessageEvent('message',{source,data:{type:'kitvi:request',requestId:'blocked',method:'storage.get',params:{key:'test'}}}))})()`);
    await until('!document.querySelector("iframe")', 'global revocation removes frame');
    assert.equal(await js('window.fixture.calls.filter(call=>call[0]==="invoke").length'), 0);
    check('both gates required and synchronous revocation blocks iframe bridge');
    await click(`document.querySelector('input[aria-label="플러그인 사용"]')`); await until('window.fixture.state().system.enabled', 'subsequent direct re-enable');
    assert.equal(await js('!!document.querySelector("dialog")'), false);
    await click(button('열기')); await until('!!document.querySelector("iframe")', 'reopened plugin');
    await js(`window.fixture.changePlugin({contentHash:'b'.repeat(64),enabled:false,needsConsent:true,authorEmail:undefined})`);
    await until('!document.querySelector("iframe")', 'changed plugin removes frame');
    await click(`document.querySelector('input[aria-label="Consent fixture 사용"]')`); await until('!!document.querySelector("dialog[open]")', 'new consent notice');
    assert.match(await js('document.querySelector("dialog").textContent'), /연락처 미등록/);
    await click(modalButton('동의하고 활성화')); await until('!document.querySelector("dialog")', 'new hash accepted');
    assert.equal(await js('window.fixture.calls.filter(call=>call[0]==="accept").at(-1)[2]'), 'b'.repeat(64));
    check('changed content invalidates activation and optional email has fallback');
    await click(`document.querySelector('input[aria-label="플러그인 사용"]')`); await until('!!document.querySelector("dialog[open]")', 'disable confirmation');
    assert.match(await js('document.querySelector("dialog").textContent'), /진행 중/);
    await click(modalButton('취소')); await until('!document.querySelector("dialog")', 'disable cancellation');
    assert.equal(await js('window.fixture.state().system.enabled'), true);
    await click(`document.querySelector('input[aria-label="플러그인 사용"]')`); await until('!!document.querySelector("dialog[open]")', 'disable repeat');
    await click(modalButton('플러그인 사용 끄기')); await until('!window.fixture.state().system.enabled', 'disable confirmed');
    check('global disable explains stopped work and supports cancellation');
    await js('window.fixture.staleRemount()'); await wait(80);
    await js(`window.fixture.emit({system:{enabled:false,acceptedAt:new Date().toISOString()}});window.fixture.resolveInitial()`);
    await wait(80);
    assert.equal(await js(`document.querySelector('input[aria-label="플러그인 사용"]').checked`), false);
    assert.equal(await js('!!document.querySelector("iframe")'), false);
    check('late initial snapshot cannot undo newer global revocation');
    for (const appearance of ['light', 'dark']) {
      win.setSize(680, 740); await js(`window.fixture.theme('${appearance}')`); await wait(100);
      await click(`document.querySelector('input[aria-label="플러그인 사용"]')`); await until('window.fixture.state().system.enabled', 'compact usage');
      await js('window.fixture.changePlugin({enabled:false,needsConsent:true})'); await wait(50);
      await click(`document.querySelector('input[aria-label="Consent fixture 사용"]')`); await until('!!document.querySelector("dialog[open]")', 'compact notice');
      assert.equal(await js(`(()=>{const d=document.querySelector('dialog'),b=d.getBoundingClientRect();return b.left>=0&&b.right<=innerWidth&&b.top>=0&&b.bottom<=innerHeight&&d.scrollWidth<=d.clientWidth+1})()`), true);
      await js('document.fonts.ready'); await wait(180);
      assert.equal(await js('getComputedStyle(document.querySelector("dialog")).colorScheme'), appearance);
      writeFileSync(join(__dirname, `artifacts/plugin-consent-${appearance}.png`), (await win.capturePage()).toPNG());
      await click(modalButton('취소')); await until('!document.querySelector("dialog")', 'compact cancel');
      await js('window.fixture.emit({system:{enabled:false,acceptedAt:new Date().toISOString()}})'); await wait(40);
    }
    check('light and dark compact dialogs fit viewport');
    report.result = 'PASS';
  } catch (error) { report.error = error.stack || String(error); }
  writeFileSync(join(__dirname, 'artifacts/plugin-consent-ui.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2)); clearTimeout(watchdog); app.exit(report.result === 'PASS' ? 0 : 1);
});
